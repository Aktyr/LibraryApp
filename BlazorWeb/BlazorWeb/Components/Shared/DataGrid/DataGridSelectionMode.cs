namespace BlazorWeb.Components.Shared.DataGrid;

/// <summary>
/// Режим выделения строк в гриде.
/// Влияет на наличие колонки чекбоксов и на поведение клика по строке.
/// </summary>
public enum DataGridSelectionMode
{
    /// <summary>
    /// Выделение отключено.
    /// Колонка чекбоксов и счётчик выделения не отображаются,
    /// действия над выделением недоступны.
    /// </summary>
    None,

    /// <summary>
    /// Разрешено выделять только одну строку за раз.
    /// Ctrl/Shift-модификаторы игнорируются.
    /// </summary>
    Single,

    /// <summary>
    /// Разрешено выделять несколько строк.
    /// Поддерживаются Ctrl+клик (добавить/убрать) и Shift+клик (диапазон).
    /// </summary>
    Multiple
}